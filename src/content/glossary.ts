/** يحاول يرجع الكلمة لأصلها: studies → study، played → play، playing → play */
function candidates(word: string): string[] {
    const w = word.toLowerCase().replace(/[’']s$/, '').replace(/’/g, "'")
    const out = [w]
    if (w.endsWith('ies')) out.push(w.slice(0, -3) + 'y')
    if (w.endsWith('es')) out.push(w.slice(0, -2))
    if (w.endsWith('s')) out.push(w.slice(0, -1))
    if (w.endsWith('ied')) out.push(w.slice(0, -3) + 'y')
    if (w.endsWith('ed')) out.push(w.slice(0, -2), w.slice(0, -1))
    if (w.endsWith('ing')) out.push(w.slice(0, -3), w.slice(0, -3) + 'e')
    if (w.endsWith('est')) out.push(w.slice(0, -3))
    if (w.endsWith('er')) out.push(w.slice(0, -2))
    if (w.endsWith('ly')) out.push(w.slice(0, -2))
    return out
}

export type Lookup = { word: string; base: string; entry: GlossaryEntry } | { word: string; name: true } | { word: string; missing: true }

/** يدوّر الكلمة في القاموس، وإذا ما لقاها بشكلها يجرب أصلها */
export function lookup(word: string): Lookup {
    for (const c of candidates(word)) {
        if (G[c]) return { word, base: c, entry: G[c] }
    }
    if (NAMES.has(word.toLowerCase().replace(/[’']s$/, ''))) return { word, name: true }
    return { word, missing: true }
}
