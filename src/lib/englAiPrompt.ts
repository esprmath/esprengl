/** قائمة دروس الموقع عشان الذكاء يربط كل خطأ بدرسه */
export function lessonsList(items: { slug: string; title: string }[]) {
    return '\n\nدروس الموقع (slug: العنوان):\n' + items.map((i) => `${i.slug}: ${i.title}`).join('\n')
}

