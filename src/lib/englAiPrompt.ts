/** معلومات الدرس اللي يكون فيه الطالب، تنضاف للبرومت عشان يعرف السياق */
export function lessonContext(ctx: { course?: string; topic?: string; lesson?: string }) {
    const parts = [
        ctx.course && `المادة: ${ctx.course}`,
        ctx.topic && `العنوان: ${ctx.topic}`,
        ctx.lesson && `الدرس: ${ctx.lesson}`,
    ].filter(Boolean)
    return parts.length ? `\n\nالطالب الحين في:\n${parts.join('\n')}` : ''
}

